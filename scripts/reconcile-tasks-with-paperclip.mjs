#!/usr/bin/env node
// Reconcile ticket IDs in tasks/CURRENT-SPRINT.md and tasks/BACKLOG.md
// against the live Paperclip board. Pure Node 22 ESM, no deps.

import { readFile, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const SPRINT_PATH = resolve(REPO_ROOT, "tasks/CURRENT-SPRINT.md");
const BACKLOG_PATH = resolve(REPO_ROOT, "tasks/BACKLOG.md");
const REPORT_PATH = resolve(REPO_ROOT, "tasks/reconciliation-2026-05-05.md");
const TICKET_RE = /\b([A-Z]{2,5}-\d+)\b/g;

function parseArgs(argv) {
  const out = { dryRun: false, baseUrl: null };
  for (const a of argv.slice(2)) {
    if (a === "--dry-run") out.dryRun = true;
    else if (a.startsWith("--base-url=")) out.baseUrl = a.slice("--base-url=".length);
  }
  return out;
}

function extractIds(text) {
  const ids = new Set();
  let m;
  while ((m = TICKET_RE.exec(text)) !== null) ids.add(m[1]);
  return ids;
}

function idCmp(a, b) {
  const [pa, na] = a.split("-");
  const [pb, nb] = b.split("-");
  if (pa !== pb) return pa < pb ? -1 : 1;
  return Number(na) - Number(nb);
}

function locationFor(id, sprintIds, backlogIds) {
  const inS = sprintIds.has(id), inB = backlogIds.has(id);
  if (inS && inB) return "CURRENT-SPRINT.md + BACKLOG.md";
  return inS ? "CURRENT-SPRINT.md" : "BACKLOG.md";
}

function classify(status) {
  const s = String(status || "").toLowerCase();
  if (s === "completed" || s === "closed" || s === "done") return "CLOSED-IN-API";
  return "STILL-OPEN";
}

async function probeId(baseUrl, id) {
  const url = `${baseUrl.replace(/\/$/, "")}/api/issues/${id}`;
  let res;
  try {
    res = await fetch(url, { headers: { accept: "application/json" } });
  } catch (err) {
    const code = err && (err.cause?.code || err.code);
    if (code === "ECONNREFUSED" || code === "ENOTFOUND" || code === "ETIMEDOUT") {
      const e = new Error(`paperclip-unreachable: ${code}`);
      e.unreachable = true;
      throw e;
    }
    throw err;
  }
  if (res.status === 404) return { kind: "NOT-FOUND", status: "404" };
  if (!res.ok) return { kind: "ERROR", status: `HTTP ${res.status}` };
  let body;
  try { body = await res.json(); } catch { return { kind: "ERROR", status: "invalid JSON" }; }
  const status = body?.status ?? body?.issue?.status ?? body?.data?.status ?? "unknown";
  return { kind: classify(status), status };
}

const row = (cols) => `| ${cols.join(" | ")} |`;

function buildReport({ all, sprintIds, backlogIds, results, dryRun, baseUrl }) {
  const closed = [], open = [], missing = [], errors = [];
  for (const id of [...all].sort(idCmp)) {
    const r = results.get(id);
    const loc = locationFor(id, sprintIds, backlogIds);
    if (!r) continue;
    if (r.kind === "CLOSED-IN-API") closed.push({ id, loc, status: r.status });
    else if (r.kind === "STILL-OPEN") open.push({ id, loc, status: r.status });
    else if (r.kind === "NOT-FOUND") missing.push({ id, loc });
    else errors.push({ id, loc, status: r.status });
  }
  const L = [];
  L.push(`# Tasks reconciliation - ${new Date().toISOString()}`, "");
  L.push("Generated by `scripts/reconcile-tasks-with-paperclip.mjs`. Compares ticket");
  L.push("IDs in tasks/CURRENT-SPRINT.md + tasks/BACKLOG.md against the Paperclip board.", "");
  L.push(`- Base URL: ${dryRun ? "(dry-run, not contacted)" : baseUrl}`);
  L.push(`- Total unique IDs: ${all.size} (sprint=${sprintIds.size}, backlog=${backlogIds.size})`, "");
  if (dryRun) {
    L.push("## Inventory (dry-run)", "", row(["ID", "Doc location"]), row(["---", "---"]));
    for (const id of [...all].sort(idCmp)) L.push(row([id, locationFor(id, sprintIds, backlogIds)]));
    L.push("");
    return L.join("\n");
  }
  L.push("## Closed in API (candidates to remove from sprint/backlog)", "");
  L.push(row(["ID", "Doc location", "API status"]), row(["---", "---", "---"]));
  for (const r of closed) L.push(row([r.id, r.loc, r.status]));
  L.push("", "## Still open in API", "");
  L.push(row(["ID", "Doc location", "API status"]), row(["---", "---", "---"]));
  for (const r of open) L.push(row([r.id, r.loc, r.status]));
  L.push("", "## Not found in API (likely external/legacy refs)", "");
  L.push(row(["ID", "Doc location"]), row(["---", "---"]));
  for (const r of missing) L.push(row([r.id, r.loc]));
  L.push("");
  if (errors.length) {
    L.push("## API errors", "", row(["ID", "Doc location", "Error"]), row(["---", "---", "---"]));
    for (const r of errors) L.push(row([r.id, r.loc, r.status]));
    L.push("");
  }
  return L.join("\n");
}

async function main() {
  const args = parseArgs(process.argv);
  const baseUrl = args.baseUrl || process.env.PAPERCLIP_BASE_URL || "http://localhost:3030";
  const [sprintText, backlogText] = await Promise.all([
    readFile(SPRINT_PATH, "utf8"),
    readFile(BACKLOG_PATH, "utf8"),
  ]);
  const sprintIds = extractIds(sprintText);
  const backlogIds = extractIds(backlogText);
  const all = new Set([...sprintIds, ...backlogIds]);
  const results = new Map();
  let closed = 0, open = 0, missing = 0;
  if (!args.dryRun) {
    for (const id of all) {
      try {
        const r = await probeId(baseUrl, id);
        results.set(id, r);
        if (r.kind === "CLOSED-IN-API") closed++;
        else if (r.kind === "STILL-OPEN") open++;
        else if (r.kind === "NOT-FOUND") missing++;
      } catch (err) {
        if (err && err.unreachable) {
          process.stderr.write(`Paperclip not running at ${baseUrl}. Start it or rerun with --dry-run.\n`);
          process.exit(2);
        }
        results.set(id, { kind: "ERROR", status: String(err?.message || err) });
      }
    }
  }
  const report = buildReport({ all, sprintIds, backlogIds, results, dryRun: args.dryRun, baseUrl });
  await writeFile(REPORT_PATH, report, "utf8");
  if (args.dryRun) {
    process.stdout.write(`RECONCILE: total=${all.size} closed=0 open=0 missing=0 (dry-run)\n`);
  } else {
    process.stdout.write(`RECONCILE: total=${all.size} closed=${closed} open=${open} missing=${missing}\n`);
  }
}

main().catch((err) => {
  process.stderr.write(`reconcile failed: ${err?.stack || err}\n`);
  process.exit(1);
});
